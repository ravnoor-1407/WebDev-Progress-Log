// Not-A-Number(NaN) in JavaScript
// NaN is a special value in JavaScript that represents a value that is "Not-a-Number".
// It is typically the result of an invalid mathematical operation, such as dividing zero by zero or taking the square root of a negative number.

console.log(0 / 0);
console.log(typeof (0 / 0));

console.log(NaN + 1);
console.log(typeof (NaN + 1));

console.log(NaN - 1);
console.log(typeof (NaN - 1));

console.log(NaN * 1);
console.log(typeof (NaN * 1));

console.log(NaN + NaN);
console.log(typeof (NaN + NaN));

console.log(NaN ** NaN);
console.log(typeof (NaN ** NaN));