// undefined and null in JavaScript

// undefined is a primitive value that has not been assigned a value.
// It is the default value of uninitialized variables, function parameters that are not provided, and missing properties of objects.

let x;
console.log(x); // Output: undefined

// null is a primitive value that represents the intentional absence of any object value.
// It is often used to indicate that a variable should have no value or that an object property does not exist.

let y = null;
console.log(y); // Output: null