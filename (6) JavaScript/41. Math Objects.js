// Math Objects in JavaScript 
// The JavaScript Math object is a built-in, global object used to perform mathematical operations on numbers.

// Math properties
console.log(Math.E); // Euler's number
console.log(Math.PI); // Ratio of cicle's circumference to its diameter
console.log(Math.SQRT1_2); // Square root of ½
console.log(Math.LN10); // Natural logarithm of 10
console.log(Math.LN2); // Natural logarithm of 2\
console.log(Math.LOG10E); // Base-10 logarithm of E
console.log(Math.LOG2E); // Base-2 logarithm of E

// Math methods

// a) Absolute value function
console.log(Math.abs(12));
console.log(Math.abs(-12));

// b) Power function
console.log(Math.pow(2, 4));

// c) Floor function (value less than or equal)
console.log(Math.floor(5));
console.log(Math.floor(-5));
console.log(Math.floor(5.987));
console.log(Math.floor(-5.987));

// d) Ceil function (value greater than or equal)
console.log(Math.ceil(5));
console.log(Math.ceil(-5));
console.log(Math.ceil(5.987));
console.log(Math.ceil(-5.987));

// e) Random function (gives random value ranging from 0 to 1)
console.log(Math.random());
console.log(Math.random());