// Assignment Operators in JavaScript
// Assignment operators are used to assign values to variables. The most common assignment operator is the equal sign (=), but there are also compound assignment operators that combine an arithmetic operation with assignment.

// Basic Assignment
let num = 10; // Assigns the value 10 to the variable num
console.log("Initial value of num:", num); // Output: 10

// Compound Assignment Operators
num += 5; // Equivalent to num = num + 5
console.log("After += 5, num:", num); // Output: 15

num -= 3; // Equivalent to num = num - 3
console.log("After -= 3, num:", num); // Output: 12

num *= 2; // Equivalent to num = num * 2
console.log("After *= 2, num:", num); // Output: 24

num /= 4; // Equivalent to num = num / 4
console.log("After /= 4, num:", num); // Output: 6