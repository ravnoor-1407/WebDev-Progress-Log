// console.log() in JavaScript
// The console.log() method is used to print messages to the console. It is commonly used for debugging purposes and to display information during the execution of a program.

// You can log strings, numbers, variables, and even expressions using console.log().
console.log("Hello, World!");
console.log("This is a message logged to the console.");

// You can also log variables and expressions
let num = 54321;
console.log("The value of num is:", num);

// You can log arithmetic operations and expressions
console.log("The sum of 5 and 10 is:", 5 + 10);

// You can log multiple values in a single console.log() statement
console.log("Hello", "world!", "Let's start this journey of learning JavaScript. On count of", num, "Hurray!");