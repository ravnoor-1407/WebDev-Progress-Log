// Identifier Rules in JavaScript

// All JavaScript variables must be identified with unique names (identifiers).
// The rules for naming identifiers are as follows:
// 1. Identifiers can contain letters, digits, underscores, and dollar signs with no spaces.
// 2. Identifiers must begin with a letter, underscore (_), or dollar sign ($).
// 3. Identifiers are case-sensitive (e.g., myVar and myvar are different).
// 4. Reserved words (like JavaScript keywords) cannot be used as identifiers.

// Examples of valid identifiers:
let myVar = 10;
let _myVar = 20;
let $myVar = 30;
let myVar2 = 40;

// Examples of invalid identifiers:
// let 2myVar = 50; // Invalid: starts with a digit
// let my Var = 60; // Invalid: contains a space
// let var = 70; // Invalid: 'var' is a reserved word

//camelCase is a common convention for naming identifiers in JavaScript.
// In camelCase, the first word is lowercase and subsequent words are capitalized (e.g., myVariableName).

//snake_case is another convention where words are separated by underscores (e.g., my_variable_name).

//PascalCase is a convention where the first letter of each word is capitalized (e.g., MyVariableName).