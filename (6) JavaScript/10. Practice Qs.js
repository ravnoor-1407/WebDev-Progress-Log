// Practice Questions for JavaScript Assignment & Unary Operators

// Q1. What is the value of each variable in each line of code?
let num = 5;
let newNum = num++; // newNum = 5, num = 6
newNum = ++num; // newNum = 7, num = 7

// Q2. What will be the output of the following code?
let a = 10;
let b = a++ + ++a; // b = 10 + 12 = 22, a = 12
console.log("Value of b:", b); // Output: 22
console.log("Value of a:", a); // Output: 12