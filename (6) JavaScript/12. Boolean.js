// Boolean Values in JavaScript
// In JavaScript, a boolean is a data type that can have one of two values: true or false.
// Boolean values are often used in conditional statements and logical operations.

// Example of boolean values:
let isJavaScriptFun = true;
let isCodingHard = false;

// Boolean values can be used in conditional statements:
if (isJavaScriptFun) {
    console.log("JavaScript is fun!");
} else {
    console.log("JavaScript is not fun.");
}

// Boolean values can also be the result of comparisons:
let x = 10;
let y = 20;
let isXGreaterThanY = x > y; // false
console.log("Is x greater than y?", isXGreaterThanY); // Output: false