// Nested OR Multi-dimensional Arrays in JavaScript
// An array that contain one or more arrays as its elements.

let nums = [[1, 1], [2, 4], [3, 6], [4, 8], [5, 10]];
console.log(nums);

// Accesing nested array
console.log(nums[0]);
console.log(nums[1]);
console.log(nums[2]);
console.log(nums[3]);
console.log(nums[4]);

// Accessing Nested array's elements
console.log(nums[0][0], nums[0][1]);
console.log(nums[1][0], nums[1][1]);
console.log(nums[2][0], nums[2][1]);
console.log(nums[3][0], nums[3][1]);
console.log(nums[4][0], nums[4][1]);